#!/usr/bin/env bash
# Make sure the server's private .env exists and has a JWT signing key.
# Called by deploy/deploy.sh before anything else; safe to run any number of
# times.
#
# * Never overwrites or reorders existing lines - it only appends what is missing.
# * Never prints a secret value (only variable names).
# * Never creates DATABASE_URL: database credentials must be added by a person.
set -euo pipefail
cd "$(dirname "$0")/.."

# Files created here are readable by the owner only.
umask 077

if [ ! -f .env ]; then
  touch .env
  echo "Created an empty .env (owner read/write only)."
fi
chmod 600 .env
[ -f backend/.env ] && chmod 600 backend/.env

has_value() { grep -qsE "^[[:space:]]*$1=.+" .env backend/.env; }

if has_value JWT_SECRET_KEY; then
  echo "JWT_SECRET_KEY: present (kept unchanged)."
else
  secret="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))' 2>/dev/null \
    || openssl rand -hex 48)"
  [ -n "$secret" ] || { echo "Could not generate JWT_SECRET_KEY." >&2; exit 1; }
  # Start on a new line even if the file does not end with one.
  [ -s .env ] && [ "$(tail -c1 .env)" != "" ] && echo >> .env
  printf '# Generated by deploy/ensure-env.sh on %s\nJWT_SECRET_KEY=%s\n' \
    "$(date -u +%Y-%m-%d)" "$secret" >> .env
  unset secret
  echo "JWT_SECRET_KEY: was missing - generated a new random key in .env."
  echo "               Users with an existing session will need to sign in again."
fi

# An empty override in the server files would silently switch a feature off,
# because they take precedence over deploy/production.env.
for name in AWS_REGION S3_BUCKET_NAME DYNAMODB_ACTIVITY_TABLE; do
  if grep -qsE "^[[:space:]]*${name}=[[:space:]]*$" .env backend/.env; then
    echo "WARNING: ${name} is set to an empty value in .env or backend/.env," \
      "which overrides deploy/production.env. Remove that line."
  fi
done
