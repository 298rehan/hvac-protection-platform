"""The `photos` table - metadata for images stored in the private S3 bucket.

Only the object key and verified metadata live here. The image bytes are never
stored in MySQL or DynamoDB.
"""

from datetime import datetime

from sqlalchemy import CheckConstraint, Enum as SAEnum, ForeignKey, Integer, String
from sqlalchemy.orm import Mapped, mapped_column

from app.database.session import Base
from app.database.types import UTCDateTime, current_timestamp_6, utcnow
from app.models.enums import PhotoCategory, PhotoStatus


class Photo(Base):
    __tablename__ = "photos"
    __table_args__ = (
        # A photo belongs to exactly one AC unit or one service request.
        CheckConstraint(
            "(ac_unit_id IS NULL) <> (service_request_id IS NULL)",
            name="ck_photos_single_owner",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    # The customer whose equipment the photo shows - used for access checks.
    customer_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    ac_unit_id: Mapped[int | None] = mapped_column(
        ForeignKey("ac_units.id", ondelete="CASCADE"), index=True
    )
    service_request_id: Mapped[int | None] = mapped_column(
        ForeignKey("service_requests.id", ondelete="CASCADE"), index=True
    )
    category: Mapped[PhotoCategory] = mapped_column(
        SAEnum(PhotoCategory, name="photo_category", values_callable=lambda e: [m.value for m in e]),
        nullable=False,
    )
    status: Mapped[PhotoStatus] = mapped_column(
        SAEnum(PhotoStatus, name="photo_status", values_callable=lambda e: [m.value for m in e]),
        default=PhotoStatus.PENDING,
        nullable=False,
        index=True,
    )

    # Always generated by the backend - never taken from the client.
    s3_key: Mapped[str] = mapped_column(String(512), unique=True, nullable=False)
    original_filename: Mapped[str] = mapped_column(String(255), nullable=False)
    declared_content_type: Mapped[str] = mapped_column(String(100), nullable=False)
    # Filled in once the backend has checked the stored object's size and bytes.
    content_type: Mapped[str | None] = mapped_column(String(100))
    size_bytes: Mapped[int | None] = mapped_column(Integer)

    uploaded_by_user_id: Mapped[int | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime, default=utcnow, server_default=current_timestamp_6(), nullable=False
    )
    confirmed_at: Mapped[datetime | None] = mapped_column(UTCDateTime)

    def __repr__(self) -> str:  # pragma: no cover - debugging helper
        return f"<Photo {self.id} {self.category.value} {self.status.value}>"
